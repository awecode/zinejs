// Embed the bundled page-flip sound into src/sound/clip.ts as a base64 data URI.
//
// Reads packages/core/assets/flip.mp3 (source only, not shipped) and writes src/sound/clip.ts.
// Inlining avoids any bundler URL resolution and any network fetch for the default clip. Rerun
// (`pnpm --filter @zinejs/core embed-clip`) whenever the asset changes.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assetPath = join(root, 'assets', 'flip.mp3');
const outPath = join(root, 'src', 'sound', 'clip.ts');

if (!existsSync(assetPath)) {
  console.error(`embed-flip-clip: no asset at ${assetPath}. Drop a short mp3 there and rerun.`);
  process.exit(1);
}

const bytes = readFileSync(assetPath);
const dataUri = `data:audio/mpeg;base64,${bytes.toString('base64')}`;

const header = `/**
 * The bundled default page-flip sound, as a base64 \`data:\` URI.
 *
 * Generated by \`scripts/embed-flip-clip.mjs\` from \`packages/core/assets/flip.mp3\` — do not
 * hand-edit. Inlined rather than shipped as a separate asset so the default clip needs no bundler
 * URL resolution and no network fetch (works offline / under strict CSP); consumers who want an
 * external file use the \`sound.url\` option instead.
 */
`;

writeFileSync(outPath, `${header}export const FLIP_CLIP = '${dataUri}';\n`);
console.log(`embed-flip-clip: embedded ${bytes.length} bytes → ${outPath}`);
